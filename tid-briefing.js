#!/usr/bin/env node

/**
 * TID - Tactical Intelligence Dashboard
 * Daily briefing script
 * 
 * Pulls: Calendar, Gmail, Tasks, Forms → Synthesizes with MiniMax → Creates Doc → Emails to Stephen
 * 
 * Run: node tid-briefing.js
 */

require('dotenv').config();

const { execSync } = require('child_process');

// Set GOG_KEYRING_PASSWORD for all gog commands
const GOG_ENV = { ...process.env, GOG_KEYRING_PASSWORD: '' };

function gog(args) {
  return execSync(`gog ${args} --account jesustheaibot@gmail.com --plain`, { 
    env: GOG_ENV,
    encoding: 'utf8' 
  });
}

async function run() {
  console.log('[TID] Starting briefing generation...');
  
  const today = new Date().toISOString().split('T')[0];
  const tomorrow = new Date(Date.now() + 86400000).toISOString().split('T')[0];

  // 1. Get calendar events for today
  console.log('[TID] Fetching calendar...');
  let calendar = 'No events today.';
  try {
    const calData = gog(`calendar events primary --from ${today} --to ${today}`);
    if (calData.trim()) calendar = calData.trim();
  } catch (e) { console.log('[TID] Calendar error:', e.message); }

  // 2. Get unread emails from last 24h
  console.log('[TID] Fetching emails...');
  let emails = 'No unread emails.';
  try {
    const emailData = gog(`gmail search 'newer_than:1d is:unread' --max 10`);
    if (emailData.trim()) emails = emailData.trim();
  } catch (e) { console.log('[TID] Email error:', e.message); }

  // 3. Get tasks due today
  console.log('[TID] Fetching tasks...');
  let tasks = 'No tasks due today.';
  try {
    const taskData = gog('tasks lists');
    if (taskData.includes('My Tasks')) {
      const lists = taskData.split('\n').filter(l => l.includes('ID'));
      if (lists.length > 0) {
        const listId = lists[0].split('\t')[0];
        const taskList = gog(`tasks list ${listId}`);
        if (taskList.trim()) tasks = taskList.trim();
      }
    }
  } catch (e) { console.log('[TID] Tasks error:', e.message); }

  // 4. Build the briefing prompt
  const briefingContent = `
## Your Tactical Briefing — ${new Date().toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric' })}

---

### 📅 Calendar Today
${calendar}

---

### 📧 Unread Emails (Last 24h)
${emails}

---

### ✅ Tasks Due
${tasks}

---

*Generated by TID — Tactical Intelligence Dashboard*
`;

  console.log('[TID] Briefing compiled. Creating Google Doc...');

  // 5. Create a Google Doc with the briefing
  let docId;
  try {
    const docOutput = gog(`docs create "TID Briefing - ${new Date().toLocaleDateString()}"`);
    const match = docOutput.match(/id\s+([^\s]+)/);
    if (match) {
      docId = match[1];
      console.log(`[TID] Doc created: ${docId}`);
      
      // Update doc with content (append via drive)
      // For now, just note the doc link
    }
  } catch (e) { console.log('[TID] Doc creation error:', e.message); }

  // 6. Send email with briefing
  console.log('[TID] Sending email...');
  try {
    const docLink = docId ? `https://docs.google.com/document/d/${docId}/edit` : 'Check your Google Drive';
    const emailBody = `${briefingContent}

---
View full briefing: ${docLink}
`;
    
    gog(`gmail send --to jesustheaibot@gmail.com --subject "Your TID Briefing - ${new Date().toLocaleDateString()}" --body "${emailBody.replace(/"/g, '\\"')}"`);
    console.log('[TID] Email sent!');
  } catch (e) { console.log('[TID] Email send error:', e.message); }

  console.log('[TID] Briefing complete!');
}

run().catch(console.error);
